/**
 * Embeds the static Archivo TTF instances from /public/fonts/pdf into
 * lib/pdf/fonts-data.ts as base64 data URLs.
 * File path: /scripts/generate-pdf-fonts.mjs
 *
 * Why: @react-pdf/renderer runs inside a Vercel function whose file
 * system only contains what the build tracer decided to ship; a font
 * that is not there fails the whole quote PDF. Data URLs travel inside
 * the JavaScript bundle itself, so nothing on disk is needed at runtime.
 * Re-run after replacing a font file:  node scripts/generate-pdf-fonts.mjs
 * test/pdf/fonts-data.test.ts fails when the module and the files drift.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(new URL(".", import.meta.url).pathname, "..");
const dir = path.join(root, "public", "fonts", "pdf");
const FILES = [
  ["ArchivoRegular", "Archivo-Regular.ttf"],
  ["ArchivoMedium", "Archivo-Medium.ttf"],
  ["ArchivoBold", "Archivo-Bold.ttf"],
  ["ArchivoExpandedBold", "ArchivoExpanded-Bold.ttf"],
  ["ArchivoExpandedBlack", "ArchivoExpanded-Black.ttf"],
];

let out = `/**
 * GENERATED by scripts/generate-pdf-fonts.mjs — do not edit by hand.
 * File path: /lib/pdf/fonts-data.ts
 *
 * The static Archivo TTF instances from /public/fonts/pdf as base64 data
 * URLs, so the quote PDF renderer never depends on font files being
 * present on the serverless file system (see lib/pdf/fonts.ts).
 * SERVER ONLY — never import from a client component (~800 KB).
 */

export type PdfFontData = { file: string; sha256: string; dataUrl: string };

`;
for (const [name, file] of FILES) {
  const bytes = readFileSync(path.join(dir, file));
  const sha = createHash("sha256").update(bytes).digest("hex");
  out += `export const ${name}: PdfFontData = {\n  file: ${JSON.stringify(file)},\n  sha256: ${JSON.stringify(sha)},\n  dataUrl:\n    "data:font/ttf;base64,${bytes.toString("base64")}",\n};\n\n`;
}
out += `export const PDF_FONT_FILES: readonly PdfFontData[] = [${FILES.map(([n]) => n).join(", ")}];\n`;
writeFileSync(path.join(root, "lib", "pdf", "fonts-data.ts"), out);
console.log(`wrote lib/pdf/fonts-data.ts (${(out.length / 1024).toFixed(0)} KB)`);
